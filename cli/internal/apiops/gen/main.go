// Command gen writes ops_gen.go. It reads the client interface in api/gen/api.gen.go and makes
// one function per operationId, so the CLI calls every operation through the generated client.
// Run from the repository root: go run ./cli/internal/apiops/gen
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strings"
)

var line = regexp.MustCompile(`^\t([A-Z]\w+)\(ctx context\.Context, (.*)reqEditors \.\.\.RequestEditorFn\)`)

func main() {
	src, err := os.ReadFile("api/gen/api.gen.go")
	if err != nil {
		fatal(err)
	}
	text := string(src)
	start := strings.Index(text, "type ClientInterface interface {")
	end := strings.Index(text[start:], "\n}\n")
	block := text[start : start+end]

	type method struct{ name, args string }
	all := map[string]method{}
	for _, l := range strings.Split(block, "\n") {
		m := line.FindStringSubmatch(l)
		if m == nil {
			continue
		}
		all[m[1]] = method{m[1], m[2]}
	}
	// Prefer the WithBody variant when it exists.
	ops := map[string]method{}
	for name, m := range all {
		if strings.HasSuffix(name, "WithBody") {
			ops[strings.TrimSuffix(name, "WithBody")] = m
		}
	}
	for name, m := range all {
		if _, ok := ops[name]; !ok && !strings.HasSuffix(name, "WithBody") {
			if strings.Contains(m.args, "JSONRequestBody") || strings.Contains(m.args, "FormdataBody") {
				continue
			}
			ops[name] = m
		}
	}
	names := make([]string, 0, len(ops))
	for n := range ops {
		names = append(names, n)
	}
	sort.Strings(names)

	var b bytes.Buffer
	b.WriteString("// Code generated by cli/internal/apiops/gen. DO NOT EDIT.\n\n")
	b.WriteString("// SPDX-License-Identifier: Apache-2.0\n\npackage apiops\n\n")
	b.WriteString("import (\n\t\"bytes\"\n\t\"context\"\n\t\"net/http\"\n\n\t\"github.com/polipan/polipan/api/gen\"\n)\n\n")
	b.WriteString("var _ = bytes.NewReader\n\n")
	b.WriteString("// calls maps an operationId to a call of the generated client.\n")
	b.WriteString("var calls = map[string]func(ctx context.Context, c *gen.Client, in Input, ed gen.RequestEditorFn) (*http.Response, error){\n")
	for _, n := range names {
		m := ops[n]
		opID := strings.ToLower(n[:1]) + n[1:]
		var call []string
		pi := 0
		for _, a := range strings.Split(strings.TrimSuffix(strings.TrimSpace(m.args), ","), ",") {
			a = strings.TrimSpace(a)
			if a == "" {
				continue
			}
			f := strings.Fields(a)
			if len(f) != 2 {
				fatal(fmt.Errorf("cannot read argument %q of %s", a, n))
			}
			switch {
			case f[0] == "contentType":
				call = append(call, "in.ContentType")
			case f[0] == "body":
				call = append(call, "bytes.NewReader(in.Body)")
			case f[0] == "params":
				call = append(call, "&gen."+strings.TrimPrefix(f[1], "*")+"{}")
			case f[1] == "Version":
				call = append(call, fmt.Sprintf("in.Int(%d)", pi))
				pi++
			default:
				call = append(call, fmt.Sprintf("in.Str(%d)", pi))
				pi++
			}
		}
		method := n
		if _, ok := all[n+"WithBody"]; ok {
			method = n + "WithBody"
		}
		args := append([]string{"ctx"}, call...)
		args = append(args, "ed")
		fmt.Fprintf(&b, "\t%q: func(ctx context.Context, c *gen.Client, in Input, ed gen.RequestEditorFn) (*http.Response, error) {\n\t\treturn c.%s(%s)\n\t},\n", opID, method, strings.Join(args, ", "))
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		fatal(err)
	}
	if err := os.WriteFile("cli/internal/apiops/ops_gen.go", out, 0o644); err != nil {
		fatal(err)
	}
	fmt.Println("operations:", len(names))
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, err)
	os.Exit(1)
}
